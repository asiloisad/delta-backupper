import { readFile, writeFile, access } from "node:fs/promises";
import { createHash } from "node:crypto";
import path from "node:path";
import { root } from "./build.mjs";

const nodeVersion = process.versions.node;
let nodeLicense;
for (const candidate of [path.join(path.dirname(process.execPath), "LICENSE"), path.join(path.dirname(process.execPath), "../LICENSE")]) {
  try { nodeLicense = await readFile(candidate, "utf8"); break; } catch { /* official binary layout differs by OS */ }
}
if (!nodeLicense) {
  const response = await fetch(`https://raw.githubusercontent.com/nodejs/node/v${nodeVersion}/LICENSE`, { signal: AbortSignal.timeout(30_000) });
  if (!response.ok) throw new Error(`Cannot obtain Node ${nodeVersion} license: ${response.status}`);
  nodeLicense = await response.text();
}
const lock = JSON.parse(await readFile(path.join(root, "package-lock.json"), "utf8"));
const sections = [
  "Delta Backupper — third-party notices\n\nGenerated by script/notices.mjs. Own source is licensed separately in LICENSE.\n",
  await readFile(path.join(root, "script/vendor/theme-NOTICES"), "utf8"),
  `Node.js ${nodeVersion}\nSource: https://github.com/nodejs/node/tree/v${nodeVersion}\nComponent: embedded CLI runtime (SEA).\nSHA-256 of license: ${createHash("sha256").update(nodeLicense).digest("hex")}\n\n${nodeLicense}`,
];
for (const [relative, info] of Object.entries(lock.packages)) {
  if (!relative || info.dev || info.link || !relative.includes("node_modules/")) continue;
  const directory = path.join(root, relative);
  const metadata = JSON.parse(await readFile(path.join(directory, "package.json"), "utf8"));
  let text;
  for (const name of ["LICENSE", "LICENSE.md", "LICENSE.txt", "LICENSE-MIT", "LICENSE-MIT.txt", "LICENCE", "license", "license.md", "license.txt"]) {
    try { text = await readFile(path.join(directory, name), "utf8"); break; } catch { /* try conventional license filenames */ }
  }
  if (!text) throw new Error(`Missing complete license text for runtime dependency ${metadata.name}@${metadata.version}`);
  sections.push(`${metadata.name} ${metadata.version}\nSource: ${typeof metadata.repository === "string" ? metadata.repository : metadata.repository?.url ?? metadata.homepage ?? "https://www.npmjs.com/package/" + metadata.name}\nDeclared license: ${metadata.license}\n\n${text}`);
}
const electron = JSON.parse(await readFile(path.join(root, "node_modules/electron/package.json"), "utf8"));
sections.push(`Electron ${electron.version}\nSource: https://github.com/electron/electron/tree/v${electron.version}\nComponent: desktop runtime.\n\n${await readFile(path.join(root, "node_modules/electron/LICENSE"), "utf8")}`);
const chromiumPath = path.join(root, "node_modules/electron/dist/LICENSES.chromium.html");
await access(chromiumPath);
// Preserve the upstream notice verbatim; it accompanies the desktop distribution too.
sections.push(`Chromium and Electron bundled components\nSource revision: Electron ${electron.version} distribution.\nThe following is the complete upstream LICENSES.chromium.html, retained verbatim.\n\n${await readFile(chromiumPath, "utf8")}`);
sections.push(`NSIS 3.12 — local Windows installer stub, Modern UI 2, zlib compression and built-in nsExec, nsDialogs and System plug-ins\nSource: https://github.com/NSIS-Dev/nsis/tree/v312\nBuild bundle: electron-builder-binaries nsis@1.2.1, https://github.com/electron-userland/electron-builder-binaries/releases/tag/nsis%401.2.1\nBundle SHA-256: 56997fdefe25e7928a1a68b4583d08b240b66cf660234053b20131a74cc082f4\nDelta's installer uses the NSIS core, Modern UI 2 and built-in nsExec, nsDialogs and System; Modern UI 2 copyright 2002-2026 Joost Verburg, contributors Amir Szekely and Anders Kjersem; it does not embed community extraction/UAC plugins. The complete upstream license follows, including compression modules not selected by Delta.\n\n${await readFile(path.join(root, "script/vendor/nsis-LICENSE"), "utf8")}`);
await writeFile(path.join(root, "THIRD_PARTY_NOTICES"), sections.join("\n\n============================================================\n\n") + "\n");
console.log(`Generated THIRD_PARTY_NOTICES (${sections.length} component sections).`);
